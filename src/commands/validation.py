"""Validation of the untrusted arguments the client sends with each command.

Everything in a command comes from the client, so handlers must check types, ranges
and sizes before touching the player's save. A failed check raises ``CommandRejected``:
the command is skipped, the save is left untouched and the rejection is logged.
"""
import math
import re
from typing import Any, Iterable, NoReturn, Optional

MAX_SAFE_INT = 2 ** 53
MAX_NAME_LENGTH = 32
MAX_COORDINATE = 4095
MAX_SMALL_INT = 100000
_INT_TEXT = re.compile(r"-?\d{1,18}")
_CONTROL_CHARS = re.compile(r"[\x00-\x1f\x7f]")


class CommandRejected(Exception):
    """The client sent something the server refuses to apply."""


def reject(reason: str) -> NoReturn:
    raise CommandRejected(reason)


def to_int(value: Any, name: str, minimum: int = -MAX_SAFE_INT, maximum: int = MAX_SAFE_INT) -> int:
    if isinstance(value, bool):
        reject(f"{name} must be an integer")
    if isinstance(value, int):
        number = value
    elif isinstance(value, float) and value.is_integer():
        number = int(value)
    elif isinstance(value, str) and _INT_TEXT.fullmatch(value.strip()):
        number = int(value.strip())
    else:
        reject(f"{name} must be an integer")
    if not minimum <= number <= maximum:
        reject(f"{name} is out of range ({minimum}..{maximum})")
    return number


def to_uid(value: Any, name: str) -> int:
    """An identifier generated by the client (egg, dragon, building)."""
    return to_int(value, name, 1, MAX_SAFE_INT)


def to_flag(value: Any, name: str) -> int:
    number = to_int(value, name, 0, 1)
    return number


def to_text(value: Any, name: str, max_length: int = MAX_NAME_LENGTH, allow_empty: bool = False) -> str:
    if not isinstance(value, str):
        reject(f"{name} must be text")
    text = _CONTROL_CHARS.sub("", value).strip()
    if len(text) > max_length:
        reject(f"{name} is longer than {max_length} characters")
    if not text and not allow_empty:
        reject(f"{name} must not be empty")
    return text


def to_iso_id(value: Any, name: str = "iso id") -> str:
    """Keys of ``map.items``: positive integers kept as text."""
    return str(to_int(value, name, 1, MAX_SAFE_INT))


def one_of(value: Any, allowed: Iterable[Any], name: str) -> Any:
    allowed = tuple(allowed)
    if value not in allowed:
        reject(f"{name} must be one of {allowed}")
    return value


def check_json_depth(value: Any, name: str, max_depth: int = 4, max_items: int = 64) -> None:
    """Reject deeply nested or huge client-provided JSON before it is stored."""
    stack = [(value, 0)]
    seen = 0
    while stack:
        current, depth = stack.pop()
        seen += 1
        if depth > max_depth or seen > max_items:
            reject(f"{name} is too large or too deeply nested")
        if isinstance(current, dict):
            for key, item in current.items():
                if not isinstance(key, str) or key.startswith("$") or "." in key:
                    reject(f"{name} contains an invalid key")
                stack.append((item, depth + 1))
        elif isinstance(current, list):
            stack.extend((item, depth + 1) for item in current)
        elif isinstance(current, str):
            if len(current) > 256:
                reject(f"{name} contains a text that is too long")
        elif isinstance(current, float):
            if not math.isfinite(current) or abs(current) > MAX_SAFE_INT:
                reject(f"{name} contains an invalid number")
        elif isinstance(current, int) and abs(current) > MAX_SAFE_INT:
            reject(f"{name} contains an invalid number")


def optional(args: list, index: int) -> Optional[Any]:
    return args[index] if len(args) > index else None
